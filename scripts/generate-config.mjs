import fs from 'node:fs';
import path from 'node:path';

const rootDir = process.cwd();
const envPath = path.join(rootDir, '.env');
const targetConfigPath = path.join(rootDir, 'public', 'assets', 'js', 'config.js');

// Parse .env if it exists
function parseEnv(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const content = fs.readFileSync(filePath, 'utf-8');
  const env = {};
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      let val = trimmed.slice(eqIdx + 1).trim();
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      env[key] = val;
    }
  }
  return env;
}

const fileEnv = parseEnv(envPath);
// Prioritize process.env (Vercel / CI) then fallback to .env file
const getEnv = (key, fallback = '') => process.env[key] || fileEnv[key] || fallback;

const config = {
  SUPABASE_URL: getEnv('SUPABASE_URL'),
  SUPABASE_ANON_KEY: getEnv('SUPABASE_ANON_KEY'),
  TABLE_NAME: getEnv('TABLE_NAME', 'customer_submissions'),
  SALES_TABLE_NAME: getEnv('SALES_TABLE_NAME', 'sales_master'),
  ACTIVITY_TABLE_NAME: getEnv('ACTIVITY_TABLE_NAME', 'sales_activities'),
  PENJUALAN_TABLE_NAME: getEnv('PENJUALAN_TABLE_NAME', 'penjualan'),
  STORAGE_BUCKET: getEnv('STORAGE_BUCKET', 'customer-photos'),
  WILAYAH_API_BASE_URL: getEnv('WILAYAH_API_BASE_URL', 'https://www.emsifa.com/api-wilayah-indonesia/api'),
  REVERSE_GEOCODE_URL: getEnv('REVERSE_GEOCODE_URL', '')
};

const fileContent = `// Auto-generated by scripts/generate-config.mjs from .env or environment variables.
// Do not edit this file manually.
window.APP_CONFIG = ${JSON.stringify(config, null, 2)};
`;

fs.mkdirSync(path.dirname(targetConfigPath), { recursive: true });
fs.writeFileSync(targetConfigPath, fileContent, 'utf-8');
console.log('Successfully generated public/assets/js/config.js');
